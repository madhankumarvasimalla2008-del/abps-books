async function runRouteTests() {
  console.log('\nRunning Admin Shipments Route & Page Tests...');
  let failures = 0;

  const routesToTest = [
    {
      path: '/admin/shipments',
      name: 'Shipments Directory List Page',
      expectedText: 'Shipment Management',
      shouldMatch: true,
    },
    {
      path: '/admin/shipments/shp-1',
      name: 'Shipment Detail Page (shp-1)',
      expectedText: 'SHP-2026-1091',
      shouldMatch: true,
    },
    {
      path: '/admin/shipments/shp-2',
      name: 'Shipment Detail Page (shp-2)',
      expectedText: 'SHP-2026-1092',
      shouldMatch: true,
    },
    {
      path: '/admin/shipments/shp-invalid-99999',
      name: 'Shipment Detail Fallback (Invalid ID)',
      expectedText: 'Shipment Record Not Found',
      shouldMatch: true,
    },
    {
      path: '/tracking?trackingNumber=BD-88392019',
      name: 'Customer Tracking Page Compatibility',
      expectedText: 'Track Order',
      shouldMatch: true,
    },
  ];

  for (const route of routesToTest) {
    try {
      const res = await getPage(route.path);
      const textMatches = res.body.toLowerCase().includes(route.expectedText.toLowerCase());
      if (res.status === 200 && textMatches) {
        console.log(`✅ [HTTP 200] ${route.name} (${route.path}) matched "${route.expectedText}"`);
      } else {
        console.error(
          `❌ [HTTP ${res.status}] ${route.name} (${route.path}) - match: ${textMatches} (expected "${route.expectedText}")`
        );
        failures++;
      }
    } catch (err) {
      console.error(`❌ Failed to request ${route.path}: ${err.message}`);
      failures++;
    }
  }

  return failures === 0;
}

