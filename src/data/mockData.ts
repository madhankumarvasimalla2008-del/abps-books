export function createMockTimeline(status: string): OrderTrackingStep[] {
  const steps = [
    { status: 'Pending', label: 'Order Placed', description: 'Order has been recorded' },
    { status: 'Confirmed', label: 'Confirmed', description: 'Order details verified' },
    { status: 'Processing', label: 'Processing', description: 'Order is being prepared' },
    { status: 'Shipped', label: 'Shipped', description: 'Order dispatched for delivery' },
    { status: 'Delivered', label: 'Delivered', description: 'Order delivered' },
  ];

  /* Simple logic to mark completed and current */
  const states = ['Pending', 'Confirmed', 'Processing', 'Shipped', 'Delivered'];
  const currentIndex = states.indexOf(status);

  return steps.map((step, index) => ({
    ...step,
    status: step.status as any,
    completed: currentIndex >= 0 ? index <= currentIndex : index === 0,
    current: currentIndex >= 0 ? index === currentIndex : false,
    timestamp: currentIndex >= 0 && index <= currentIndex ? new Date(Date.now() - (10 - index) * 86400000).toISOString() : undefined,
  }));
}

